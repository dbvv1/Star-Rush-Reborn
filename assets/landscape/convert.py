"""Bake the two CC0 OBJ silhouettes into deterministic renderer-neutral triangles.

Run from the repository root: python3 assets/landscape/convert.py
No textures, material files, downloads, runtime loaders or Blender dependency.
"""
from pathlib import Path
import json
import math

ROOT = Path(__file__).resolve().parent
NAMES = ("rock_largeA", "rock_tallB")


def convert(name):
    vertices, faces = [], []
    for line in (ROOT / "source" / f"{name}.obj").read_text().splitlines():
        fields = line.split()
        if not fields:
            continue
        if fields[0] == "v":
            point = list(map(float, fields[1:]))
            assert len(point) == 3 and all(math.isfinite(v) for v in point)
            vertices.append(point)
        elif fields[0] == "f":
            face = [int(item.split("/")[0]) - 1 for item in fields[1:]]
            assert len(face) == 3, "These fixed source OBJs are triangulated"
            faces.append(face)
    lo = [min(p[k] for p in vertices) for k in range(3)]
    hi = [max(p[k] for p in vertices) for k in range(3)]
    assert all(hi[k] > lo[k] for k in range(3))
    # Full width/depth is one unit, foot at y=0, peak y=1; preserve winding.
    points = [[(p[k] - lo[k]) / (hi[k] - lo[k]) - (0 if k == 1 else .5)
               for k in range(3)] for p in vertices]
    for face in faces:
        assert all(0 <= i < len(points) for i in face)
        a, b, c = [points[i] for i in face]
        u, v = [[p[k] - a[k] for k in range(3)] for p in (b, c)]
        normal = [u[1]*v[2]-u[2]*v[1], u[2]*v[0]-u[0]*v[2], u[0]*v[1]-u[1]*v[0]]
        assert math.hypot(*normal) > 1e-9, "Degenerate source triangle"
    return {"name": name, "p": [round(v, 7) for p in points for v in p],
            "i": [i for face in faces for i in face]}


result = [convert(name) for name in NAMES]
(ROOT / "coastal-rocks.js").write_text(
    "// Kenney Nature Kit 2.1, CC0. Generated by assets/landscape/convert.py.\n"
    "// Geometry only; the game chooses placement and muted coast colors.\n"
    "const coastalRockData=" + json.dumps(result, separators=(",", ":")) + ";\n")
print("Coastal rock triangles:", [len(x["i"]) // 3 for x in result])
